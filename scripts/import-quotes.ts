// Converts the Claude Artifact JSON export into a SQL file for D1.
//
// Usage:
//   npm run import -- path/to/export.json > data/import.sql
//   npx wrangler d1 execute quote-trax --remote --file=data/import.sql
//
// Run it once against an empty database. Re-running it will fail on duplicate keys.
// Report lines go to stderr. Review them before loading.
import { readFileSync } from "node:fs";

type SourceBook = { id: string; title: string; author: string; series: string | null };
type SourceQuote = { id: string; text: string; bookId: string; page: string | null; added: string };
type Source = { books: SourceBook[]; quotes: SourceQuote[] };

const file = process.argv[2];
if (!file) {
  console.error("Usage: npm run import -- <export.json>");
  process.exit(1);
}

const data = JSON.parse(readFileSync(file, "utf8")) as Source;

// Escapes a value as a SQL string literal. Empty or missing values become NULL.
function lit(value: string | null | undefined): string {
  if (value === null || value === undefined || value.trim() === "") return "NULL";
  return `'${value.replace(/'/g, "''")}'`;
}

// Trailing attribution such as "- Roque" or "-Lysander" at the end of a quote.
// The dash must follow whitespace or closing punctuation, so hyphens inside
// words ("full-strength", "cat-like") don't match.
const ATTRIBUTION = /(?:\s+|(?<=[.!?”"’]))[-–—]\s*([^\n]{2,120})$/;

const out: string[] = ["-- generated by scripts/import-quotes.ts"];

// Series: one row per distinct book series.
const seriesNames = [...new Set(data.books.map((b) => b.series).filter((s): s is string => !!s))];
const seriesIds = new Map<string, string>();
seriesNames.forEach((name, i) => {
  const id = `series-${i + 1}`;
  seriesIds.set(name, id);
  out.push(`INSERT INTO series (id, name) VALUES (${lit(id)}, ${lit(name)});`);
});

// Books. series_position is left NULL. Fill it in later from your own list.
for (const b of data.books) {
  const seriesId = b.series ? lit(seriesIds.get(b.series)!) : "NULL";
  out.push(
    `INSERT INTO books (id, title, author, series_id, series_position) VALUES ` +
      `(${lit(b.id)}, ${lit(b.title)}, ${lit(b.author)}, ${seriesId}, NULL);`,
  );
}

// Quotes.
const bookIds = new Set(data.books.map((b) => b.id));
for (const q of data.quotes) {
  if (!bookIds.has(q.bookId)) {
    console.error(`SKIP ${q.id}: unknown bookId ${q.bookId}`);
    continue;
  }

  let text = q.text.trim();
  let attribution: string | null = null;
  const match = text.match(ATTRIBUTION);
  if (match && match.index !== undefined && match.index > 0) {
    attribution = match[1].trim();
    text = text.slice(0, match.index).trimEnd();
    console.error(`ATTRIBUTION ${q.id}: "${attribution}"`);
  }

  // Flags single line breaks inside a paragraph. Some are intentional (chat, verse);
  // many are copy-paste wraps. These are kept as-is until you decide.
  if (/[^\n]\n[^\n]/.test(text)) {
    console.error(`SINGLE-BREAK ${q.id}: ${text.slice(0, 60).replace(/\n/g, "⏎")}...`);
  }

  out.push(
    `INSERT INTO quotes (id, book_id, text, page, attribution, created_at) VALUES ` +
      `(${lit(q.id)}, ${lit(q.bookId)}, ${lit(text)}, ${lit(q.page)}, ${lit(attribution)}, ${lit(q.added)});`,
  );
}

console.error(
  `\n${data.books.length} books, ${seriesNames.length} series, ${data.quotes.length} quotes processed.`,
);
console.log(out.join("\n"));
